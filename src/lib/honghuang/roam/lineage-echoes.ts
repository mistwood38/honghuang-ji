/** An echo can only refer to a recognized choice made before the chapter being read. */
export function lineageEcho(
  origin: Origin,
  stage: number,
  history: { chapter: number; choice: string }[],
): string | null {
  const echo = ECHOES[origin]?.[stage];
  if (!echo || echo.from >= stage) return null;
  const entry = history.find((row) => row.chapter === echo.from && row.chapter < stage);
  return entry && Object.hasOwn(echo.choices, entry.choice) ? echo.choices[entry.choice]! : null;
}
