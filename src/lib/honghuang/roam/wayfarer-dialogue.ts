export function wayfarerScene(save: SaveData, id: string, topic: TalkTopic): WayfarerScene | null {
  const world = save.world;
  if (!world || !Object.hasOwn(VOICES, id) || !["road", "past", "promise"].includes(topic))
    return null;
  const actor = world.living.people[id];
  if (!actor || actor.place !== world.place) return null;
  const voice = VOICES[id]!,
    errand = world.living.errands[id],
    relation = world.relations[id] ?? 0,
    destination = errand ? ROAM_PLACES[errand.destination]?.name : "";
  let memory: string | null = actor.met ? `你与${voice.name}已经打过照面。` : null;
  if (errand?.stage === "carrying")
    memory = `你接下了送往${destination}的${GOODS[voice.good]}托付，还未送达。`;
  else if (errand?.stage === "delivered")
    memory = `你已把${GOODS[voice.good]}送到${destination}，回信尚未交还。`;
  else if (errand?.stage === "done" && errand.count > 0)
    memory = `你已替${voice.name}完成 ${errand.count} 次托付。`;

  let paragraphs: string[];
  if (topic === "road") {
    const region = world.living.regions[world.place],
      ruin = world.living.sites[`${world.place}-ruin`];
    const land =
      (region?.strain ?? 0) >= 3
        ? "strained"
        : ruin?.state === "stripped"
          ? "stripped"
          : ruin?.state === "mending"
            ? "mending"
            : ruin?.state === "restored"
              ? "restored"
              : "quiet";
    paragraphs = [actor.met ? voice.again : voice.first, voice.road, voice.land[land]];
  } else if (topic === "past") {
    paragraphs = [...(relation >= 4 ? voice.trustedPast : voice.past)];
  } else {
    const stage =
      errand?.stage === "done" && errand.count >= 2 ? "returned" : (errand?.stage ?? "none");
    paragraphs = voice.promise[stage].map((line) => line.replaceAll("{destination}", destination));
  }
  return { title: voice.titles[topic], paragraphs, memory };
}
