export function realmOf(dao: number) {
  let cur = REALMS[0]!;
  for (const realm of REALMS) {
    if (dao >= realm.min) cur = realm;
  }
  return cur;
}

export function nextRealm(dao: number) {
  return REALMS.find((realm) => realm.min > dao) ?? null;
}

